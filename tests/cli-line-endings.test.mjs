import { testGitConfig } from '../.pbai4devs/scripts/lib/test-git-environment.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { appendFileSync, existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { syncBuiltinESMExports } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { applyPlan, planInstallation } from '../src/install.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cli = join(repo, 'bin/agentdevkit.mjs');
const node24 = Number(process.versions.node.split('.')[0]) >= 24 && !process.versions.bun;
const cliTimeout = process.platform === 'win32' ? 240000 : 120000;

test('CLI preserva referência CRLF já satisfeita sem duplicar bloco ou alterar índice', { skip: !node24 ? 'A CLI do kit requer Node.js 24 ou superior nesta fixture.' : false, timeout: process.platform === 'win32' ? 900000 : 180000 }, t => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'adk-cli-eol-')));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const env = { ...Object.fromEntries(Object.entries(process.env).filter(([key]) => !/^GIT_/i.test(key))), GIT_CONFIG_GLOBAL: testGitConfig, GIT_CONFIG_NOSYSTEM: '1', GIT_OPTIONAL_LOCKS: '0', GIT_TERMINAL_PROMPT: '0' };
  const run = (program, args, timeout = 120000) => spawnSync(program, args, { cwd: root, env, encoding: 'utf8', timeout, maxBuffer: 8 * 1024 * 1024 });
  const git = (...args) => { const r = run('git', args); assert.equal(r.status, 0, r.stderr); };
  const command = (...args) => {
    const result = run(process.execPath, [cli, ...args, '--target', root, '--json'], cliTimeout);
    const details = `${args.join(' ')}: ${result.error?.message || result.signal || ''}\n${result.stderr}\n${result.stdout}`;
    assert.equal(result.error, undefined, details);
    assert.equal(result.signal, null, details);
    return { ...result, result: JSON.parse(result.stdout) };
  };
  git('init', '-q', '--template=');
  writeFileSync(join(root, '.gitignore'), '# fixture\n');
  git('add', '.gitignore');
  assert.equal(command('init', '--agents', 'claude', '--yes').status, 0);
  const pointer = '.claude/skills/criar-skill/SKILL.md', source = '.pbai4devs/skills/projeto/criar-skill/SKILL.md';
  const file = join(root, pointer);
  writeFileSync(file, readFileSync(file, 'utf8').replaceAll('\n', '\r\n'));
  appendFileSync(join(root, source), '\nNota sintética para teste.\n');
  const prior = readFileSync(file), sourceBytes = readFileSync(join(root, source));
  const tracked = ['.git/index', '.git/config', '.git/info/exclude', '.gitignore'];
  const read = p => existsSync(join(root, p)) ? readFileSync(join(root, p)) : null;
  const before = new Map(tracked.map(p => [p, read(p)]));
  const state = new Map(['.pbai4devs/state/agentdevkit.json', '.pbai4devs/state/derived.json'].map(p => [p, read(p)]));
  const check = command('sync', '--check');
  assert.equal(check.status, 1);
  assert.ok(check.result.preserved.some(item => item.path === pointer && ['existing-reference-satisfied', 'edited-managed-file'].includes(item.reason)));
  assert.ok(!check.result.plan.some(item => item.path === pointer));
  assert.deepEqual(readFileSync(file), prior);
  assert.deepEqual(readFileSync(join(root, source)), sourceBytes);
  for (const [p, bytes] of [...before, ...state]) assert.deepEqual(read(p), bytes, p);
  const plan = planInstallation({ target: root, mode: 'sync', language: 'pt' });
  assert.equal(plan.canApply, true);
  assert.ok(plan.stageDependencies.some(item => item.path === pointer));
  const changed = Buffer.concat([prior, Buffer.from('\r\nEdição humana após o plano.\r\n')]);
  writeFileSync(file, changed);
  assert.throws(() => applyPlan(plan), error => error.code === 'E_CHANGED');
  assert.deepEqual(readFileSync(file), changed);
  for (const [p, bytes] of [...before, ...state]) assert.deepEqual(read(p), bytes, p);
  writeFileSync(file, prior);
  const sourcePlan = planInstallation({ target: root, mode: 'sync', language: 'pt' });
  assert.equal(sourcePlan.canApply, true);
  appendFileSync(join(root, source), '\nEdição da fonte após o plano.\n');
  const changedSourceBytes = readFileSync(join(root, source));
  assert.throws(() => applyPlan(sourcePlan), error => error.code === 'E_CHANGED');
  assert.deepEqual(readFileSync(join(root, source)), changedSourceBytes);
  assert.deepEqual(readFileSync(file), prior);
  for (const [p, bytes] of [...before, ...state]) assert.deepEqual(read(p), bytes, p);
  writeFileSync(join(root, source), sourceBytes);
  const backupPlan = planInstallation({ target: root, mode: 'sync', language: 'pt' });
  assert.equal(backupPlan.canApply, true);
  const originalWrite = fs.writeFileSync;
  const backupEdit = Buffer.concat([sourceBytes, Buffer.from('\nEdição durante backup.\n')]);
  let injected = false, failure;
  t.mock.method(fs, 'writeFileSync', (filename, ...args) => {
    if (!injected && typeof filename === 'string' && filename.includes(`${sep}.agent-tests${sep}agentdevkit${sep}backups${sep}`)) {
      injected = true;
      originalWrite(join(root, source), backupEdit);
    }
    return originalWrite(filename, ...args);
  });
  syncBuiltinESMExports();
  try { applyPlan(backupPlan); } catch (error) { failure = error; }
  finally { t.mock.restoreAll(); syncBuiltinESMExports(); }
  assert.equal(injected, true, 'a fixture deve alcançar o backup');
  assert.equal(failure?.code, 'E_CHANGED');
  const preservedBackup = failure?.uncertainPaths?.find(path => path.includes('.agent-tests/agentdevkit/backups/'));
  assert.ok(preservedBackup && existsSync(join(root, preservedBackup)), 'backup deve permanecer disponível para revisão');
  assert.deepEqual(readFileSync(join(root, source)), backupEdit);
  assert.deepEqual(readFileSync(file), prior);
  for (const [p, bytes] of [...before, ...state]) assert.deepEqual(read(p), bytes, p);
  const pending = command('recovery');
  assert.equal(pending.status, 0);
  assert.equal(pending.result.recovery.status, 'pending');
  assert.equal(command('sync').result.error?.code, 'E_RECOVERY_PENDING');
  writeFileSync(join(root, source), sourceBytes);
  const { generation, id } = pending.result.recovery;
  assert.equal(command('recovery', 'resolve', String(generation), id).status, 0);
  const applied = command('sync');
  assert.equal(applied.status, 0);
  const after = readFileSync(file);
  assert.deepEqual(after, prior);
  const assertNotAdopted = () => {
    const installed = JSON.parse(readFileSync(join(root, '.pbai4devs/state/agentdevkit.json')));
    assert.notEqual(installed.files?.[pointer], createHash('sha256').update(prior).digest('hex'));
    assert.equal(installed.blocks?.[pointer], undefined);
  };
  assertNotAdopted();
  assert.deepEqual(readFileSync(join(root, source)), sourceBytes);
  for (const [p, bytes] of before) assert.deepEqual(read(p), bytes, p);
  assert.equal(command('sync').status, 0);
  assert.deepEqual(readFileSync(file), after);
  assertNotAdopted();
  for (const [p, bytes] of before) assert.deepEqual(read(p), bytes, p);
  const changedSource = readFileSync(join(root, source), 'utf8').replace(/^description: .+$/m, 'description: Descrição sintética alterada.');
  assert.notEqual(changedSource, sourceBytes.toString('utf8'));
  writeFileSync(join(root, source), changedSource);
  const changedCheck = command('sync', '--check');
  assert.equal(changedCheck.status, 1);
  assert.ok(changedCheck.result.plan.some(item => item.path === pointer));
  assert.deepEqual(readFileSync(file), prior);
  assert.equal(command('sync').status, 0);
  const extended = readFileSync(file);
  assert.deepEqual(extended.subarray(0, prior.length), prior);
  assert.ok(extended.subarray(prior.length).includes(Buffer.from('<!-- BEGIN AGENTDEVKIT -->')));
  for (const [p, bytes] of before) assert.deepEqual(read(p), bytes, p);
});
